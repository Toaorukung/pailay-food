export type StringKey = keyof (typeof STRINGS)['th'];

export const LOCALE_LABELS: Record<Locale, string> = {
  th: 'ไทย',
  en: 'English',
  zh: '中文',
};

/** Substitutes {placeholders}. Missing keys fall back to Thai, then the key. */
export function translate(
  locale: Locale,
  key: StringKey,
  vars?: Record<string, string | number>,
): string {
  const table = STRINGS[locale] as Record<string, string>;
  const raw = table[key] ?? (STRINGS.th as Record<string, string>)[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
